create table arbomachine.project (
    order_date date,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    owner_id bigint not null,
    updated_at timestamp(6) with time zone not null,
    site_address varchar(500),
    client_name varchar(255),
    description text,
    name varchar(255) not null,
    primary key (id)
);

create table arbomachine.project_reference_layer (
    feature_count integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    project_id bigint not null,
    source_crs varchar(32),
    source_format varchar(32) not null,
    geojson text not null,
    name varchar(255) not null,
    source_file_name varchar(255),
    primary key (id)
);

create table arbomachine.tree (
    crown_diameter_m numeric(5,2),
    height_m numeric(5,2),
    latitude numeric(10,7),
    location_accuracy_m numeric(7,2),
    location_altitude_m numeric(7,2),
    longitude numeric(10,7),
    trunk_circumference_cm integer,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    project_id bigint not null,
    updated_at timestamp(6) with time zone not null,
    location_source varchar(32) check (location_source in ('MANUAL','MAP','DEVICE_GNSS','IMPORT')),
    map_symbol_code varchar(64),
    inventory_number varchar(100) not null,
    condition_notes text,
    hazard_notes text,
    notes text,
    species_latin varchar(255),
    species_polish varchar(255),
    primary key (id)
);

create table arbomachine.tree_marking (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    tree_id bigint not null,
    code varchar(64) not null,
    primary key (id),
    constraint uk_tree_marking_tree_code unique (tree_id, code)
);

create table arbomachine.tree_monitoring_record (
    inspection_date date not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    tree_id bigint not null,
    updated_at timestamp(6) with time zone not null,
    health_status varchar(32) check (health_status in ('GOOD','FAIR','POOR')),
    notes text,
    primary key (id)
);

create table arbomachine.tree_photo (
    created_at timestamp(6) with time zone not null,
    file_size_bytes bigint not null,
    id bigint generated by default as identity,
    tree_id bigint not null,
    storage_key varchar(64) not null unique,
    content_type varchar(100) not null,
    original_file_name varchar(255) not null,
    primary key (id)
);

create table arbomachine.tree_photo_annotation (
    schema_version integer not null,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    rendered_file_size_bytes bigint not null,
    tree_photo_id bigint not null unique,
    updated_at timestamp(6) with time zone not null,
    rendered_storage_key varchar(64) not null,
    rendered_content_type varchar(100) not null,
    document_json text not null,
    primary key (id)
);

create table arbomachine.tree_stand (
    area_square_meters numeric(14,2),
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    project_id bigint not null,
    updated_at timestamp(6) with time zone not null,
    source varchar(32) not null check (source in ('MANUAL','IMPORT')),
    geometry_geojson text not null,
    name varchar(255) not null,
    notes text,
    primary key (id)
);

create table arbomachine.tree_stand_tree (
    tree_id bigint not null,
    tree_stand_id bigint not null,
    primary key (tree_id, tree_stand_id)
);

create table arbomachine.tree_valuation (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    tree_id bigint not null unique,
    updated_at timestamp(6) with time zone not null,
    overall_category varchar(32) check (overall_category in ('LOW','MEDIUM','HIGH','VERY_HIGH')),
    age_value text,
    cultural_value text,
    ecological_value text,
    justification text,
    landscape_value text,
    natural_value text,
    notes text,
    primary key (id)
);

create table arbomachine.tree_work (
    completed_date date,
    planned_date date,
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    tree_id bigint not null,
    updated_at timestamp(6) with time zone not null,
    priority varchar(32) check (priority in ('LOW','NORMAL','HIGH','URGENT')),
    status varchar(32) check (status in ('RECOMMENDED','PLANNED','COMPLETED','CANCELLED')),
    map_symbol_code varchar(64),
    description text,
    name varchar(255) not null,
    primary key (id)
);

