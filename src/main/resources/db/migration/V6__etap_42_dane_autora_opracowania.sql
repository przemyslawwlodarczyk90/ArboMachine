-- Etap 42: dane autora opracowania (stale elementy dokumentu projektu), 1:1 z kontem.
create table if not exists arbomachine.document_author_profile (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) with time zone not null,
    user_account_id bigint not null unique,
    author_full_name varchar(255),
    company_name varchar(255),
    company_details text,
    methods_description text,
    qualifications text,
    primary key (id),
    constraint fk_document_author_profile_user_account foreign key (user_account_id) references arbomachine.user_account
);
